"""Host-only ABI audit between separately supplied original and rebuilt WLAN ELF."""
import contextlib
import hashlib
import importlib.util
import io
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


PAIR = load(ROOT / "scripts/audit-wlan-original-elf-pair.py", "op7t_rom_elf_pair")
FIX = load(ROOT / "tests/test_audit_wlan_built_crcs.py", "op7t_rom_elf_fixture")
RELEASE = "4.14.357-perf-g57037290bb57"
BUILT_RELEASE = RELEASE + "-dirty"


class RomWlanBinaryPairTests(unittest.TestCase):
    def setUp(self):
        # Use the same synthetic ELF and signed-module audit fixture that the
        # existing built-CRC gate uses. Never access a real phone or ROM.
        self.base = FIX.BuiltWlanSelfCrcTests(
            "test_matching_self_built_crc_is_not_installed_rom_parity"
        )
        self.base.setUp()
        self.addCleanup(self.base.doCleanups)
        self.art = self.base.art
        self.root = self.base.root
        # The built module comes from the patched worktree and carries -dirty.
        self.base.module.write_bytes(FIX.fake_arm64_module(release=BUILT_RELEASE))
        self.base.artifact_report["kernel_release"] = BUILT_RELEASE
        self.base.artifact_report["modules"][0]["sha256"] = self.base.sha()
        self.base.artifact_report["modules"][0]["size_bytes"] = (
            self.base.module.stat().st_size
        )
        self.base.compiled["wlan_module"]["sha256"] = self.base.sha()
        self.base.compiled["wlan_module"]["vermagic"] = (
            BUILT_RELEASE + " SMP modversions"
        )
        self.original = self.root / "qca_cld3_wlan.ko"
        self.original.write_bytes(
            FIX.fake_arm64_module(release=RELEASE)
        )
        self.original_sha = hashlib.sha256(self.original.read_bytes()).hexdigest()
        self.base.compiled["wlan_module"]["signer"] = "Build time autogenerated kernel key"
        self.base.compiled["wlan_module"]["signature_key_id"] = "A1B2C3"
        self.base.save()
        self.pretend_equal_signer = False

    def stub_modinfo(self, path):
        x = PAIR.ABI.inspect(path)
        original = Path(path) == self.original
        return {
            "filename": Path(path).name, "name": "wlan",
            "vermagic": x["vermagic"], "signer":
                ("Build time autogenerated kernel key"
                 if not original or self.pretend_equal_signer else "ROM official signing key"),
            "sig_key": (
                "A1B2C3" if not original or self.pretend_equal_signer else "ORIGINALKEY"
            ),
            "sig_hashalgo": "sha512", "size_bytes": Path(path).stat().st_size,
        }

    def audit(self, expected=None):
        with patch.object(PAIR.MODULES, "inspect", side_effect=self.stub_modinfo):
            return PAIR.examine(self.art, self.original, expected or self.original_sha)

    def test_reference_pair_mismatch_and_unknowns_reported(self):
        r = self.audit()
        self.assertIn("vermagic_mismatch", r["known_compatibility_blockers"])
        self.assertIn("module signature key identifiers differ", r["known_compatibility_blockers"])
        self.assertEqual(1, r["shared_symbol_crc_count"])
        self.assertEqual(0, r["mismatched_shared_symbol_crc_count"])
        self.assertTrue(r["operator_supplied_original_module_digest_matches"])
        self.assertFalse(r["operator_supplied_digest_proves_ota_provenance"])
        self.assertFalse(r["flash_ready"])
        self.assertFalse(r["installed_kernel_abi_verified"])
        self.assertFalse(r["installed_kernel_module_signing_trust_verified"])

    def test_matching_all_elf_fields_still_not_flash_ready(self):
        self.original.write_bytes(FIX.fake_arm64_module(release=BUILT_RELEASE))
        self.original_sha = hashlib.sha256(self.original.read_bytes()).hexdigest()
        self.pretend_equal_signer = True
        r = self.audit()
        self.assertEqual([], r["known_compatibility_blockers"])
        self.assertIn("installed_kernel_module_key_trust_not_verified",
                      r["unknown_verification_requirements"])
        self.assertEqual("NO_OBSERVED_ELF_MISMATCH_BUT_ROM_TRUST_UNVERIFIED",
                         r["status"])
        self.assertFalse(r["flash_ready"])

    def test_wrong_expected_digest_rejected(self):
        with self.assertRaisesRegex(PAIR.PairAuditError, "SHA-256"):
            self.audit(expected="0" * 64)

    def test_mismatched_original_crc_is_blocker(self):
        self.original.write_bytes(
            FIX.fake_arm64_module(symbols={"module_layout": 0x99998888},
                                  release=RELEASE)
        )
        self.original_sha = hashlib.sha256(self.original.read_bytes()).hexdigest()
        r = self.audit()
        self.assertIn("shared_symbol_crc_mismatch", r["known_compatibility_blockers"])
        self.assertIn("rom_symbol_crc_differs_from_built_Module.symvers",
                      r["known_compatibility_blockers"])

    def test_unsigned_original_rejected(self):
        self.original.write_bytes(FIX.fake_arm64_module(signed=False, release=RELEASE))
        self.original_sha = hashlib.sha256(self.original.read_bytes()).hexdigest()
        with self.assertRaisesRegex(PAIR.PairAuditError, "unsigned module"):
            self.audit()

    def test_symlinked_reference_module_not_accepted(self):
        other = self.root / "original-real.ko"
        self.original.rename(other)
        self.original.symlink_to(other)
        with self.assertRaises(PAIR.PairAuditError):
            self.audit()

    def test_untrusted_local_build_report_stops_comparison(self):
        self.base.artifact_report["flash_ready"] = True
        self.base.save()
        with self.assertRaises(PAIR.SELF.SelfCheckError):
            self.audit()

    def test_different_filename_rejected_even_with_matching_hash(self):
        other = self.root / "other.ko"
        other.write_bytes(self.original.read_bytes())
        with patch.object(PAIR.MODULES, "inspect", side_effect=self.stub_modinfo):
            with self.assertRaisesRegex(PAIR.PairAuditError, "original ROM"):
                PAIR.examine(self.art, other,
                             hashlib.sha256(other.read_bytes()).hexdigest())

    def test_published_ci_metadata_does_not_substitute_for_binaries(self):
        zipfiles = list(self.root.glob("*.zip"))
        self.assertEqual([], zipfiles)
        with patch.object(PAIR.MODULES, "inspect", side_effect=self.stub_modinfo):
            with self.assertRaises(PAIR.PairAuditError):
                PAIR.examine(self.art, self.root / "nonexistent.ko", "e" * 64)

    def test_cli_return_2_on_known_pair_mismatch_4_for_unknowns(self):
        args = [
            "--built-artifacts", str(self.art),
            "--original-rom-wlan", str(self.original),
            "--original-rom-sha256", self.original_sha,
        ]
        with patch.object(PAIR.MODULES, "inspect", side_effect=self.stub_modinfo):
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(2, PAIR.main(args))
        self.original.write_bytes(FIX.fake_arm64_module(release=BUILT_RELEASE))
        self.original_sha = hashlib.sha256(self.original.read_bytes()).hexdigest()
        self.pretend_equal_signer = True
        args[-1] = self.original_sha
        with patch.object(PAIR.MODULES, "inspect", side_effect=self.stub_modinfo):
            buf = io.StringIO()
            with contextlib.redirect_stdout(buf):
                self.assertEqual(4, PAIR.main(args + ["--strict"]))
        self.assertFalse(json.loads(buf.getvalue())["flash_ready"])


if __name__ == "__main__":
    unittest.main()
