class WlanReferenceReleaseGapTests(unittest.TestCase):
    def setUp(self):
        self.reference = GAP.reference()
        t = tempfile.TemporaryDirectory()
        self.addCleanup(t.cleanup)
        self.root = Path(t.name)
        self.zip = self.root / "ci.zip"

    def create_zip(self, bundle=None):
        bundle = bundle or fixture()
        with zipfile.ZipFile(self.zip, "w", compression=zipfile.ZIP_DEFLATED) as z:
            for name in GAP.ALLOWED:
                data = bundle[name]
                z.writestr(name, json.dumps(data) if isinstance(data, dict) else data)
        return self.zip

    def test_verified_real_source_context_but_not_installed_ota(self):
        self.assertEqual("hotdog", self.reference["device"])
        self.assertEqual(RELEASE, self.reference["observed_reference_wlan_vermagic_release"])
        self.assertFalse(self.reference["installed_rom_binary_identity_verified"])
        self.assertFalse(self.reference["flash_ready"])

    def test_source_build_has_known_mismatched_dirty_release(self):
        report = GAP.analyze(fixture(), self.reference)
        self.assertEqual("BLOCKED_REFERENCE_OTA_VERMAGIC_MISMATCH", report["status"])
        self.assertEqual(BUILT, report["rebuilt_wlan_release"])
        self.assertEqual(RELEASE, report["reference_wlan_release"])
        self.assertEqual(["reference_ota_wlan_vermagic_release_mismatch"],
                         report["known_compatibility_blockers"])
        self.assertEqual(394, report["internally_matched_symbol_crc_count"])
        self.assertFalse(report["flash_ready"])
        self.assertFalse(report["installed_kernel_module_signing_key_trust_verified"])

    def test_matching_release_would_still_not_approve_runtime(self):
        data = fixture()
        data["kernel.release"] = RELEASE
        data["artifact-report.json"]["kernel_release"] = RELEASE
        data["built-wlan-self-crc-report.json"]["kernel_release"] = RELEASE
        data["artifact-report.json"]["modules"][0]["vermagic"] = (
            RELEASE + " SMP preempt mod_unload modversions aarch64"
        )
        data["wlan-patch-experiment.json"]["wlan_module"]["vermagic"] = (
            data["artifact-report.json"]["modules"][0]["vermagic"]
        )
        report = GAP.analyze(data, self.reference)
        self.assertFalse(report["known_compatibility_blockers"])
        self.assertEqual("BLOCKED_UNVERIFIED_ROM_ABI_AND_KEY_TRUST", report["status"])
        self.assertFalse(report["reference_OTA_wlan_abi_verified"])
        self.assertFalse(report["flash_ready"])

    def test_module_sha_or_signer_conflict_fails(self):
        for filename, path, value in [
            ("wlan-patch-experiment.json", ("wlan_module", "sha256"), "f" * 64),
            ("artifact-report.json", ("modules", 0, "signature_key_id"), "OTHER"),
            ("wlan-patch-experiment.json", ("wlan_module", "signer"), "OTHER"),
        ]:
            data = fixture()
            obj = data[filename]
            for key in path[:-1]:
                obj = obj[key]
            obj[path[-1]] = value
            with self.subTest(path=path), self.assertRaises(GAP.ReferenceGapError):
                GAP.analyze(data, self.reference)

    def test_unproven_or_inconsistent_crc_count_rejected(self):
        for key, value in [
            ("built_module_symbols_versioned", 0),
            ("matched_against_same_build_Module_symvers", 1),
            ("mismatched_symbol_crc_count", 1),
            ("built_kernel_module_self_consistency", False),
        ]:
            data = fixture()
            data["built-wlan-self-crc-report.json"][key] = value
            with self.subTest(key=key), self.assertRaises(GAP.ReferenceGapError):
                GAP.analyze(data, self.reference)

    def test_invalidated_source_pin_or_signature_trust_claims_fail(self):
        for section, key, value in [
            ("artifact-report.json", "upstream_commit", "f" * 40),
            ("wlan-rom-source-parity.json", "rom_source_sha", "f" * 40),
            ("wlan-patch-experiment.json", "flash_ready", True),
            ("artifact-report.json", "rom_module_key_trust_verified", True),
            ("built-wlan-self-crc-report.json",
             "compared_against_actual_ROM_Module_symvers", True),
        ]:
            data = fixture()
            data[section][key] = value
            with self.subTest(key=key), self.assertRaises(GAP.ReferenceGapError):
                GAP.analyze(data, self.reference)

    def test_bounded_zip_parsing_and_strict_exit_code(self):
        self.create_zip()
        result = GAP.analyze(GAP.read_ci_zip(self.zip), self.reference)
        self.assertEqual("BLOCKED_REFERENCE_OTA_VERMAGIC_MISMATCH", result["status"])
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(0, GAP.main(["--ci-metadata-zip", str(self.zip)]))
            self.assertEqual(4, GAP.main(["--ci-metadata-zip", str(self.zip),
                                          "--strict"]))

    def test_zip_member_missing_extra_or_duplicate_rejected(self):
        self.create_zip()
        with zipfile.ZipFile(self.zip, "a") as z:
            z.writestr("secrets.txt", "do not read")
        with self.assertRaises(GAP.ReferenceGapError):
            GAP.read_ci_zip(self.zip)
        self.create_zip()
        with zipfile.ZipFile(self.zip, "a") as z:
            z.writestr("artifact-report.json", "{}")
        with self.assertRaises(GAP.ReferenceGapError):
            GAP.read_ci_zip(self.zip)

    def test_unexpected_reference_manifest_or_claim_rejected(self):
        self.assertRaises(GAP.ReferenceGapError, GAP.reference, self.root)
        cfgdir = self.root / "config"
        cfgdir.mkdir()
        rom = json.loads((ROOT / "config/rom-reference.json").read_text())
        ref = copy.deepcopy(self.reference)
        ref["installed_rom_binary_identity_verified"] = True
        (cfgdir / "rom-reference.json").write_text(json.dumps(rom))
        (cfgdir / "wlan-rom-reference-release.json").write_text(json.dumps(ref))
        with self.assertRaises(GAP.ReferenceGapError):
            GAP.reference(self.root)

    def test_no_rom_binary_or_flash_access_in_tool(self):
        text = (ROOT / "scripts/audit-wlan-reference-release.py").read_text()
        for marker in ("adb shell", "fastboot flash", "modprobe ", "insmod ",
                       "boot.img", "os.system", "subprocess.run"):
            self.assertNotIn(marker, text)
        self.assertIn('"flash_ready": False', text)


if __name__ == "__main__":
    unittest.main()
